/**
 * Builds the illustrated handoff email from its one source,
 * `Email to Rick - Admin Dashboard Handoff.md` (repo root).
 *
 *   node rick-email/build.js
 *
 * Writes, next to this file:
 *   email.html           pictures linked from img/ — open it in a browser to read
 *                        or print; for Outlook, open it, Ctrl+A, Ctrl+C and paste
 *                        into a new message (Outlook keeps the pictures)
 *   email-embedded.html  the same with every picture inside the file, so it can
 *                        be opened or forwarded on its own
 *
 * The pictures in img/ are generated by _harness/helpshots.js (with the ones
 * in admin/help-img/), never edited by hand. Edit the .md, then re-run this.
 *
 * Handles only the Markdown the email uses: "Subject:" first line, ## headings,
 * paragraphs, - and 1. lists (one nested "  - " level), **bold**, *italic*,
 * [https://…] and [text](url) links, and ![alt](rick-email/img/…) pictures.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'Email to Rick - Admin Dashboard Handoff.md');
const md = fs.readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n');

const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const C = {
  text: '#1f2937', muted: '#4b5563', navy: '#0d2d52', blue: '#005da3', orange: '#c2410c', line: '#e5e9ee',
};
const inline = (t) => esc(t)
  .replace(/\*\*(.+?)\*\*/g, `<strong style="color:${C.navy}">$1</strong>`)
  .replace(/(^|[^*])\*(?!\s)(.+?)\*/g, '$1<em>$2</em>')
  .replace(/\[(https?:[^\]]+)\](?!\()/g, `<a href="$1" style="color:${C.blue}">$1</a>`)
  .replace(/\[([^\]]+)\]\((https?:[^)]+)\)/g, `<a href="$2" style="color:${C.blue}">$1</a>`);

function build(embed) {
  const lines = md.split('\n');
  let subject = '';
  if (/^Subject:/.test(lines[0])) subject = lines.shift().replace(/^Subject:\s*/, '');
  const out = [];
  let para = [];
  let list = null; // { tag, items: [{ html, sub: [] }] }
  let afterImage = false; // a 1. list straight after a picture is its key
  const flushPara = () => {
    if (para.length) out.push(`<p style="margin:0 0 14px;line-height:1.6">${inline(para.join(' '))}</p>`);
    para = [];
  };
  const flushList = () => {
    if (!list) return;
    if (list.tag === 'ol' && list.key) {
      out.push(`<table role="presentation" cellpadding="0" cellspacing="0" style="margin:0 0 22px;border-collapse:collapse">` +
        list.items.map((it, i) => `<tr><td style="vertical-align:top;padding:0 10px 8px 0"><span style="display:inline-block;width:22px;height:22px;line-height:22px;border-radius:11px;background:${C.orange};color:#fff;font-weight:700;font-size:13px;text-align:center">${i + 1}</span></td>` +
          `<td style="vertical-align:top;padding:1px 0 8px;line-height:1.5">${it.html}</td></tr>`).join('') + `</table>`);
    } else {
      out.push(`<${list.tag} style="margin:0 0 16px;padding-left:22px;line-height:1.6">` + list.items.map((it) =>
        `<li style="margin-bottom:6px">${it.html}${it.sub.length ? `<ul style="margin:6px 0 0;padding-left:20px">${it.sub.map((x) => `<li style="margin-bottom:4px">${x}</li>`).join('')}</ul>` : ''}</li>`).join('') + `</${list.tag}>`);
    }
    list = null;
  };
  for (const raw of lines) {
    const line = raw.trimEnd();
    let m;
    if (!line.trim()) { flushPara(); continue; }
    if ((m = line.match(/^## (.+)/))) {
      flushPara(); flushList(); afterImage = false;
      out.push(`<h2 style="margin:34px 0 12px;padding-top:18px;border-top:1px solid ${C.line};font-size:20px;color:${C.navy}">${inline(m[1])}</h2>`);
      continue;
    }
    if ((m = line.match(/^!\[([^\]]*)\]\(rick-email\/(img\/[^)]+)\)/))) {
      flushPara(); flushList();
      const file = path.join(__dirname, m[2]);
      let src = m[2];
      if (embed) {
        const mime = /\.jpe?g$/i.test(file) ? 'image/jpeg' : 'image/png';
        src = `data:${mime};base64,${fs.readFileSync(file).toString('base64')}`;
      }
      out.push(`<p style="margin:6px 0 12px"><img src="${src}" alt="${esc(m[1])}" width="640" style="display:block;width:100%;max-width:640px;height:auto;border:1px solid #d9dee5;border-radius:6px"></p>`);
      afterImage = true;
      continue;
    }
    if ((m = line.match(/^  - (.+)/)) && list) {
      list.items[list.items.length - 1].sub.push(inline(m[1]));
      continue;
    }
    if ((m = line.match(/^(\d+)\. (.+)/)) || (m = line.match(/^(-) (.+)/))) {
      flushPara();
      const tag = m[1] === '-' ? 'ul' : 'ol';
      if (!list || list.tag !== tag) { flushList(); list = { tag, items: [], key: tag === 'ol' && afterImage }; }
      list.items.push({ html: inline(m[2]), sub: [] });
      continue;
    }
    flushList(); afterImage = false;
    para.push(line.trim());
  }
  flushPara(); flushList();
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(subject)}</title></head>
<body style="margin:0;padding:0;background:#f3f5f8">
<div style="max-width:680px;margin:0 auto;padding:24px 20px 40px;background:#ffffff;font-family:Segoe UI,Arial,Helvetica,sans-serif;font-size:15px;color:${C.text}">
<p style="margin:0 0 18px;font-size:13px;color:${C.muted}"><strong>Subject:</strong> ${esc(subject)}</p>
${out.join('\n')}
</div></body></html>
`;
}

fs.writeFileSync(path.join(__dirname, 'email.html'), build(false));
fs.writeFileSync(path.join(__dirname, 'email-embedded.html'), build(true));
const missing = [...md.matchAll(/\]\(rick-email\/(img\/[^)]+)\)/g)].map((m) => m[1]).filter((f) => !fs.existsSync(path.join(__dirname, f)));
if (missing.length) { console.error('missing pictures (run _harness/helpshots.js): ' + missing.join(', ')); process.exitCode = 1; }
console.log('wrote rick-email/email.html and rick-email/email-embedded.html');
