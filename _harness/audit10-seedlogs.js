/**
 * AUDIT-10 pass-5 — seed the MIRROR's two admin log files so the step-5.1
 * computed-style census actually paints every state the admin has colors for.
 *
 * Why this exists: re-running audit10-stylecensus.js on a fresh container
 * produced a census two values short of the 2026-08-09 run, and the missing
 * values were not site drift — they were admin/audit-log.php's action badges.
 * That page has ELEVEN hardcoded badge color pairs (audit-log.php:40-55) and
 * paints none of them when admin/admin-log.jsonl is absent; the same is true of
 * admin/inquiries.php's table. A census taken against empty logs silently
 * under-reports the admin's own palette, which is exactly what pass-5 is
 * counting.
 *
 * Scope: writes ONLY to _harness/site/admin/, which is the gitignored mirror
 * regenerated by sync.sh. It touches nothing under data/, so no pristine
 * restore is owed; `sh _harness/sync.sh` returns the mirror to its shipped
 * state. The entries carry the exact shape audit_log() writes
 * (admin/config.php:658) and the exact shape contact.php's ipc_log_inquiry()
 * writes, so the real renderers are exercised with real-shaped rows.
 *
 * Usage: node _harness/audit10-seedlogs.js
 */
const fs = require('fs');
const path = require('path');

const MIRROR = path.join(__dirname, 'site', 'admin');
if (!fs.existsSync(MIRROR)) {
  console.error('mirror admin/ not found — run sh _harness/sync.sh first');
  process.exit(2);
}

// One entry per action audit-log.php has a color for, plus one unknown action
// so the default badge paints too.
const ACTIONS = [
  ['add', 'IP38FE', 'created product'],
  ['edit', 'CC', 'updated specs'],
  ['delete', 'IP30HS', 'removed product'],
  ['upload-pdf', 'IP33PO', 'datasheet.pdf'],
  ['remove-pdf', 'IP33TW', 'datasheet.pdf'],
  ['upload-image', 'IP34SR', 'photo.jpg'],
  ['remove-image', 'IP44A2', 'photo.jpg'],
  ['settings', '', 'business details saved'],
  ['content', '', 'homepage copy saved'],
  ['restore', '', 'restored products-all.json backup 3'],
  ['password', '', 'admin password changed'],
  ['login', '', 'signed in'],
];

const lines = ACTIONS.map(([action, sku, detail], i) =>
  JSON.stringify({
    ts: `2026-08-0${(i % 9) + 1} 09:${String(10 + i).padStart(2, '0')}:00`,
    action, sku, detail,
    ip: '127.0.0.1',
    ua: 'Mozilla/5.0 (X11; Linux x86_64) AUDIT-10 pass-5 census seed',
  })
);
fs.writeFileSync(path.join(MIRROR, 'admin-log.jsonl'), lines.join('\n') + '\n');

// inquiries.php renders sent and failed rows differently; seed both.
const INQ = [
  { ts: '2026-08-05 11:04:12', name: 'Dana Whitfield', email: 'dana@example.com', company: 'Whitfield Cable',
    phone: '630-555-0142', subject: 'Quote request', message: 'Need 500 ft of 3/8" polyolefin heat shrink, 2:1, black. Please quote lead time.',
    sku: 'IP38FE', ip: '127.0.0.1', sent: true, kind: 'quote' },
  { ts: '2026-08-06 15:41:57', name: 'Marcus Lee', email: 'mlee@example.com', company: '', phone: '',
    subject: 'General message', message: 'Do you stock fiberglass sleeving rated above 1000F?', sku: '',
    ip: '127.0.0.1', sent: false, kind: 'general' },
];
fs.writeFileSync(path.join(MIRROR, 'inquiries.jsonl'), INQ.map((e) => JSON.stringify(e)).join('\n') + '\n');

console.log('seeded ' + lines.length + ' audit-log rows and ' + INQ.length + ' inquiries into the mirror');
console.log('  ' + path.join(MIRROR, 'admin-log.jsonl'));
console.log('  ' + path.join(MIRROR, 'inquiries.jsonl'));
