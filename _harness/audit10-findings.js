/**
 * AUDIT-10 findings validator + human-view generator.
 *
 * Validates every line of plans/audit10/state/findings.jsonl against
 * plans/audit10/findings.schema.json (structural checks implemented here —
 * no dependency install), rejects duplicate/malformed ids, enforces the
 * severity/confidence rules from severity.json, and regenerates
 * plans/audit10/state/FINDINGS.md — the human-readable table the audit
 * brief requires: URL, description, severity, screenshot path.
 *
 * Run after EVERY append. Exit 1 on any violation — a findings file that
 * does not validate must not be committed.
 *
 * Usage: node _harness/audit10-findings.js
 */
const fs = require('fs');
const path = require('path');

const STATE = path.join(__dirname, '..', 'plans', 'audit10', 'state');
const JSONL = path.join(STATE, 'findings.jsonl');
const MD = path.join(STATE, 'FINDINGS.md');

const REQUIRED = ['id', 'pass', 'severity', 'confidence', 'title', 'url', 'viewport',
  'what_it_does_to_a_real_person', 'evidence', 'reproduce', 'date'];
const SEVERITIES = ['A', 'B', 'C', 'D'];
const CONFIDENCES = ['CONFIRMED', 'LIKELY', 'INFERRED'];
const VIEWPORTS = ['desktop-1440', 'tablet-1024', 'tablet-834', 'mobile-390', 'all', 'n/a'];

const errors = [];
const findings = [];

if (!fs.existsSync(JSONL)) {
  console.log('no findings.jsonl yet — nothing to validate, writing empty FINDINGS.md');
} else {
  const lines = fs.readFileSync(JSONL, 'utf8').split('\n').filter((l) => l.trim());
  const seen = new Set();
  lines.forEach((line, i) => {
    let f;
    try { f = JSON.parse(line); } catch (e) {
      errors.push(`line ${i + 1}: not valid JSON — ${e.message}`);
      return;
    }
    const at = `line ${i + 1} (${f.id || 'no id'})`;
    for (const k of REQUIRED) if (!(k in f)) errors.push(`${at}: missing required field '${k}'`);
    if (f.id && !/^A10-[0-9]{3}$/.test(f.id)) errors.push(`${at}: id must match A10-NNN`);
    if (f.id && seen.has(f.id)) errors.push(`${at}: duplicate id`);
    if (f.id) seen.add(f.id);
    if (f.pass && !/^pass-[0-7]$/.test(f.pass)) errors.push(`${at}: bad pass '${f.pass}'`);
    if (f.severity && !SEVERITIES.includes(f.severity)) errors.push(`${at}: bad severity`);
    if (f.confidence && !CONFIDENCES.includes(f.confidence)) errors.push(`${at}: bad confidence`);
    if (f.viewport && !VIEWPORTS.includes(f.viewport)) errors.push(`${at}: bad viewport '${f.viewport}'`);
    if (['A', 'B'].includes(f.severity)) {
      if (f.confidence !== 'CONFIRMED') errors.push(`${at}: severity ${f.severity} requires confidence=CONFIRMED (severity.json rule 1)`);
      if (!f.severity_rationale) errors.push(`${at}: severity ${f.severity} requires severity_rationale`);
    }
    if (f.confidence === 'INFERRED' && ['A', 'B'].includes(f.severity)) {
      errors.push(`${at}: INFERRED caps at severity C`);
    }
    if (!f.evidence || !f.evidence.measurement) errors.push(`${at}: evidence.measurement is required — screenshots are gitignored; the number is the durable proof`);
    if (!Array.isArray(f.reproduce) || !f.reproduce.length) errors.push(`${at}: reproduce must be a non-empty array of steps`);
    if (f.date && !/^2[0-9]{3}-[0-9]{2}-[0-9]{2}$/.test(f.date)) errors.push(`${at}: bad date`);
    findings.push(f);
  });
}

if (errors.length) {
  console.error(`FAIL audit10-findings — ${errors.length} violation(s):`);
  for (const e of errors) console.error('  ' + e);
  process.exit(1);
}

// ── regenerate the human view ────────────────────────────────────────────────
const order = { A: 0, B: 1, C: 2, D: 3 };
const sorted = [...findings].sort((a, b) =>
  (order[a.severity] - order[b.severity]) || a.id.localeCompare(b.id));

let md = `# AUDIT-10 findings — generated by _harness/audit10-findings.js

**Do not edit by hand** — edit \`findings.jsonl\` and re-run the validator.
${findings.length} finding(s): `
  + SEVERITIES.map((s) => `${findings.filter((f) => f.severity === s).length} × ${s}`).join(' · ')
  + `\n\n| ID | Sev | Conf | URL | Viewport | Title | Issue screenshot |\n|---|---|---|---|---|---|---|\n`;
for (const f of sorted) {
  md += `| ${f.id} | ${f.severity} | ${f.confidence} | \`${f.url}\` | ${f.viewport} | ${f.title} | ${(f.evidence && f.evidence.issue_screenshot) || '—'} |\n`;
}
md += '\n---\n';
for (const f of sorted) {
  md += `\n## ${f.id} · [${f.severity}] ${f.title}\n\n`
    + `**URL** \`${f.url}\` · **viewport** ${f.viewport} · **confidence** ${f.confidence} · **pass** ${f.pass} · **date** ${f.date}\n\n`
    + `**What it does to a real person.** ${f.what_it_does_to_a_real_person}\n\n`
    + `**Evidence.** ${f.evidence.measurement}\n`
    + (f.evidence.issue_screenshot ? `Screenshot: \`${f.evidence.issue_screenshot}\` (gitignored; re-capture via reproduce steps if absent)\n` : '')
    + (f.evidence.probe ? `Probe: \`${f.evidence.probe}\`\n` : '')
    + `\n**Reproduce.**\n${f.reproduce.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n`
    + (f.where ? `\n**Where.** ${f.where}\n` : '')
    + (f.severity_rationale ? `\n**Severity rationale.** ${f.severity_rationale}\n` : '')
    + (f.instances && f.instances.length ? `\n**Instances (${f.instances.length}).**\n${f.instances.map((x) => `- ${x}`).join('\n')}\n` : '')
    + (f.dedupe_note ? `\n**Dedupe.** ${f.dedupe_note}\n` : '');
}
fs.mkdirSync(STATE, { recursive: true });
fs.writeFileSync(MD, md);
console.log(`ok audit10-findings — ${findings.length} finding(s) valid; FINDINGS.md regenerated`);
